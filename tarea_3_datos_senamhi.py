"""### Ejercicio 2: Datos climáticos multiestación

Crea un nuevo DataFrame con datos de 5 estaciones SENAMHI de diferentes regiones del Perú (https://www.senamhi.gob.pe/site/descarga-datos/).

Las tareas de este ejercicio ya han sido completadas en las celdas anteriores, donde se realizaron los siguientes pasos:
1. Se parsearon los nombres de las estaciones y se leyeron los archivos.
2. Se unieron los DataFrames por la columna `Fecha`.
3. Se calculó el promedio mensual de precipitación para cada estación.
4. Se identificó el mes más lluvioso en cada estación.
5. Se exportaron los resultados a archivos CSV.
"""

# Unir los DataFrames de todas las estaciones por la columna 'Fecha'
combined_df = pd.DataFrame()

for name, df_station in stations_data.items():
    # Renombrar la columna 'Pr' para incluir el nombre de la estación
    temp_df = df_station[['Pr']].rename(columns={'Pr': f'Pr_{name}'})
    if combined_df.empty:
        combined_df = temp_df
    else:
        combined_df = combined_df.join(temp_df, how='outer')

print("\nDataFrame combinado de precipitación por estación:")
print(combined_df.head())

# Calcular el promedio mensual de precipitación para cada estación
monthly_precipitation_all_stations = combined_df.resample('M').mean()

print("\nPrecipitación mensual promedio para todas las estaciones:")
print(monthly_precipitation_all_stations.head())

# Identificar el mes más lluvioso para cada estación
rainiest_month_per_station = pd.DataFrame()
for col in monthly_precipitation_all_stations.columns:
    station_name = col.replace('Pr_', '')
    if not monthly_precipitation_all_stations[col].isnull().all():
        max_pr_month = monthly_precipitation_all_stations[col].idxmax()
        max_pr_value = monthly_precipitation_all_stations[col].max()
        rainiest_month_per_station = pd.concat([
            rainiest_month_per_station,
            pd.DataFrame([{'Estacion': station_name, 'Mes_Mas_Lluvioso': max_pr_month.strftime('%Y-%m'), 'Precipitacion_Max': max_pr_value}])
        ], ignore_index=True)

print("\nMes más lluvioso por estación:")
print(rainiest_month_per_station)

# Exportar resultados a CSV
combined_df.to_csv('precipitacion_combinada_estaciones.csv')
monthly_precipitation_all_stations.to_csv('precipitacion_mensual_todas_estaciones.csv')
rainiest_month_per_station.to_csv('mes_mas_lluvioso_por_estacion.csv', index=False)

print("\nResultados multiestación exportados a CSV.")