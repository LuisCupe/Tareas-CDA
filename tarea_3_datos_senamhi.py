# Ejercicio 2: Procesamiento de datos multiestación

import pandas as pd

# Diccionario para almacenar los DataFrames de cada estación
stations_data = {}
station_names = []

# Iterar sobre cada archivo de estación
for station_file in files:
    # Extraer el código y nombre de la estación del nombre del archivo
    parts = station_file.replace('.txt', '').split('_')
    codigo_estacion = parts[0]
    nombre_estacion = ' '.join(parts[1:])
    station_names.append(nombre_estacion)

    print(f"Procesando estación: {nombre_estacion} (Código: {codigo_estacion})")

    # Construir la ruta completa del archivo
    file_path = f'/content/drive/MyDrive/SENAMHI/{station_file}'

    # Leer el archivo de la estación
    df = pd.read_table(file_path, header=None, sep=' ', na_values=['-999','-99.9'])
    df.columns = ['Año', 'Mes', 'Dia', 'Pr','Tmax', 'Tmin']

    # Formatear las columnas de fecha
    df['Año'] = df['Año'].astype(int)
    df['Mes'] = df['Mes'].astype(int)
    df['Dia'] = df['Dia'].astype(int)

    # Crear una columna de fecha para facilitar la unión y el análisis temporal
    df['Fecha'] = pd.to_datetime({'year': df['Año'], 'month': df['Mes'], 'day': df['Dia']})

    # Almacenar el DataFrame en el diccionario, usando el nombre de la estación como clave
    stations_data[nombre_estacion] = df.set_index('Fecha')

print("\nDatos de todas las estaciones cargados y preparados.")

